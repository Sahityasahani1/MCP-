"use client";

import React, { useState } from "react";
import { FileDown, BookMarked, Check, Copy, Share2 } from "lucide-react";

interface DossierExportProps {
  sessionId: string;
  papers?: any[];
  datasets?: any[];
  pipelineResult?: any;
}

export const DossierExport: React.FC<DossierExportProps> = ({
  sessionId,
  papers = [],
  datasets = [],
  pipelineResult,
}) => {
  const [copiedBib, setCopiedBib] = useState(false);

  // Generate BibTeX records
  const generateBibtex = (): string => {
    if (!papers || papers.length === 0) return "% No academic papers recorded in this session.";

    return papers
      .map((p, idx) => {
        const key = p.id ? p.id.replace(/[^a-zA-Z0-9]/g, "_") : `ref_${idx + 1}`;
        const authors = Array.isArray(p.authors) ? p.authors.join(" and ") : "Unknown";
        const year = p.published ? p.published.substring(0, 4) : new Date().getFullYear();
        const doiLine = p.doi ? `  doi       = {${p.doi}},\n` : "";
        const urlLine = p.pdf_url ? `  url       = {${p.pdf_url}},\n` : "";
        const journal = p.source ? `${p.source} Preprint` : "arXiv / OpenAlex Repository";

        return `@article{${key},\n  title     = {${p.title}},\n  author    = {${authors}},\n  year      = {${year}},\n  journal   = {${journal}},\n${doiLine}${urlLine}}`;
      })
      .join("\n\n");
  };

  // Generate Markdown Dossier
  const generateMarkdown = (): string => {
    const timestamp = new Date().toISOString();
    let md = `# AMRA Academic Research Dossier\n\n`;
    md += `> **Generated by:** Autonomous ML Research Agent (AMRA)  \n`;
    md += `> **Session ID:** \`${sessionId}\`  \n`;
    md += `> **Timestamp:** ${timestamp}  \n\n---\n\n`;

    // 1. Papers Section
    if (papers && papers.length > 0) {
      md += `## 1. Verified Peer-Reviewed Literature (${papers.length} Works)\n\n`;
      papers.forEach((p, idx) => {
        md += `### ${idx + 1}. ${p.title}\n`;
        md += `- **Authors:** ${Array.isArray(p.authors) ? p.authors.join(", ") : p.authors}\n`;
        if (p.published) md += `- **Published:** ${p.published}\n`;
        if (p.citation_count !== undefined && p.citation_count !== null) {
          md += `- **Verified Citations:** ${p.citation_count.toLocaleString()}\n`;
        }
        if (p.doi) md += `- **DOI:** [${p.doi}](https://doi.org/${p.doi})\n`;
        if (p.pdf_url) md += `- **Verified OA PDF:** [Download PDF](${p.pdf_url})\n`;
        if (p.summary) md += `\n**Abstract Summary:**\n> ${p.summary.trim()}\n\n`;
      });
      md += `---\n\n`;
    }

    // 2. Datasets Section
    if (datasets && datasets.length > 0) {
      md += `## 2. Discovered Tabular Benchmarks (${datasets.length} Datasets)\n\n`;
      datasets.forEach((d, idx) => {
        md += `### ${idx + 1}. ${d.title}\n`;
        md += `- **Dataset ID:** \`${d.dataset_id}\`\n`;
        md += `- **Source:** ${d.source || "Kaggle / Hugging Face"}\n`;
        if (d.usability_score) md += `- **Usability Score:** ${Math.round(d.usability_score * 100)}%\n`;
        if (d.size_mb) md += `- **Size:** ${d.size_mb} MB\n`;
        if (d.url) md += `- **Repository:** [View Dataset](${d.url})\n\n`;
      });
      md += `---\n\n`;
    }

    // 3. Pipeline Results Section
    if (pipelineResult) {
      md += `## 3. Data Cleaning & LightGBM Baseline Benchmark\n\n`;
      md += `- **Target Dataset:** \`${pipelineResult.output_filename || pipelineResult.dataset_name}\`\n`;
      if (pipelineResult.target_column) {
        md += `- **Inferred Target Column:** \`${pipelineResult.target_column}\`\n`;
      }
      if (pipelineResult.stats_before && pipelineResult.stats_after) {
        md += `- **Data Health Score:** ${pipelineResult.stats_before.health_score.toFixed(1)}/100 -> **${pipelineResult.stats_after.health_score.toFixed(1)}/100** (+${pipelineResult.health_score_delta?.toFixed(1)} pts)\n`;
        md += `- **Cleaned Rows / Columns:** ${pipelineResult.stats_after.rows.toLocaleString()} rows, ${pipelineResult.stats_after.cols} columns\n`;
      }
      if (pipelineResult.baseline_benchmark?.metrics) {
        md += `\n### Baseline AutoML Performance (LightGBM):\n`;
        Object.entries(pipelineResult.baseline_benchmark.metrics).forEach(([k, v]) => {
          md += `- **${k.toUpperCase()}:** ${v}\n`;
        });
      }
      if (pipelineResult.actions_taken) {
        md += `\n### Transformations Executed:\n`;
        pipelineResult.actions_taken.forEach((act: string) => {
          md += `- ${act}\n`;
        });
      }
      md += `\n---\n\n`;
    }

    // 4. BibTeX Reference Block
    md += `## 4. BibTeX Citations\n\n\`\`\`bibtex\n${generateBibtex()}\n\`\`\`\n`;
    return md;
  };

  const handleDownloadMarkdown = () => {
    const md = generateMarkdown();
    const blob = new Blob([md], { type: "text/markdown;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `AMRA_Dossier_${sessionId}.md`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const handleDownloadBibtex = () => {
    const bib = generateBibtex();
    const blob = new Blob([bib], { type: "text/plain;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `references_${sessionId}.bib`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const handleCopyBibtex = () => {
    navigator.clipboard.writeText(generateBibtex());
    setCopiedBib(true);
    setTimeout(() => setCopiedBib(false), 2000);
  };

  const hasData = (papers && papers.length > 0) || (datasets && datasets.length > 0) || pipelineResult;
  if (!hasData) return null;

  return (
    <div className="bg-[#FFFF00] text-black border-3 border-black p-3 my-3 shadow-[4px_4px_0_#000000] flex flex-wrap items-center justify-between gap-3 font-mono text-xs font-black uppercase">
      <div className="flex items-center gap-2">
        <Share2 className="w-4 h-4 text-black" aria-hidden="true" />
        <span>EXPORT RESEARCH:</span>
      </div>

      <div className="flex items-center gap-2 flex-wrap">
        <button
          onClick={handleDownloadMarkdown}
          className="bg-white text-black hover:bg-[#0000FF] hover:text-white px-3 py-1.5 border-2 border-black shadow-[2px_2px_0_#000000] inline-flex items-center gap-1.5 cursor-pointer transition-none"
          aria-label="Download research dossier as Markdown"
        >
          <FileDown className="w-3.5 h-3.5" aria-hidden="true" />
          <span>DOSSIER (.MD)</span>
        </button>

        {papers && papers.length > 0 && (
          <>
            <button
              onClick={handleDownloadBibtex}
              className="bg-white text-black hover:bg-[#00FF00] px-3 py-1.5 border-2 border-black shadow-[2px_2px_0_#000000] inline-flex items-center gap-1.5 cursor-pointer transition-none"
              aria-label="Download citations as BibTeX file"
            >
              <BookMarked className="w-3.5 h-3.5" aria-hidden="true" />
              <span>BIBTEX (.BIB)</span>
            </button>

            <button
              onClick={handleCopyBibtex}
              className="bg-white text-black hover:bg-[#FF00FF] hover:text-white px-2.5 py-1.5 border-2 border-black shadow-[2px_2px_0_#000000] inline-flex items-center gap-1 cursor-pointer transition-none"
              aria-label="Copy BibTeX citations to clipboard"
            >
              {copiedBib ? (
                <>
                  <Check className="w-3.5 h-3.5 text-green-700" aria-hidden="true" />
                  <span>COPIED</span>
                </>
              ) : (
                <>
                  <Copy className="w-3.5 h-3.5" aria-hidden="true" />
                  <span>COPY BIBTEX</span>
                </>
              )}
            </button>
          </>
        )}
      </div>
    </div>
  );
};
